#!/usr/bin/env bash
# End-to-end demo: Ranger source -> native binary -> run
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEMO_DIR="$ROOT/tmp/ranger-native-demo"

echo "????????????????????????????????????????????????????????????"
echo "?  Ranger -> LLVM IR -> native binary demo                 ?"
echo "????????????????????????????????????????????????????????????"
echo ""

echo "--- Source (tests/fixtures/llvm_main.rgr) ---"
cat "$ROOT/tests/fixtures/llvm_main.rgr"
echo ""

"$ROOT/scripts/compile-native.sh" \
  "$ROOT/tests/fixtures/llvm_main.rgr" \
  "$DEMO_DIR/main_demo" || true

echo ""
echo "Done. Try yourself:"
echo "  npm run compile:native"
echo "  ./scripts/compile-native.sh tests/fixtures/llvm_add.rgr /tmp/my_add"
echo "  /tmp/my_add; echo \$?   # -> 42"
