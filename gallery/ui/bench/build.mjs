/**
 * Bundle both sides of the bench.
 *
 * Theme and the six demo stylesheets are inlined so the page cannot drift
 * from what `npm run ui:web` paints. esbuild comes from the conformance
 * reference host — one install for the playground, the gate and this.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { assertDomInstalled, MissingDomDeps } from "../conformance/dom-adapter.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const UI = path.join(HERE, "..");
const DOM_DIR = path.join(UI, "conformance", "dom");
const domRequire = createRequire(path.join(DOM_DIR, "package.json"));

function requireDom(name) {
  try {
    assertDomInstalled();
    return domRequire(name);
  } catch (e) {
    console.error(e instanceof MissingDomDeps ? e.message : String(e));
    process.exit(3);
  }
}

for (const name of ["ui_host", "MenubarDemo", "ToolbarDemo", "SortableDemo", "MotionDemo", "TableDemo", "DropdownDemo"]) {
  if (!fs.existsSync(path.join(UI, "bin", name + ".cjs"))) {
    console.error(`compiled ${name} missing — run \`npm run ui:build\` and \`npm run ui:demo:build\``);
    process.exit(3);
  }
}

const css = (rel) => JSON.stringify(fs.readFileSync(path.join(UI, rel), "utf8"));
fs.writeFileSync(
  path.join(HERE, "generated.js"),
  "// Generated by bench/build.mjs — do not edit.\n" +
    `export const THEME_CSS = ${css("theme/base.css")};\n` +
    `export const MENUBAR_CSS = ${css("demo/menubar.css")};\n` +
    `export const TOOLBAR_CSS = ${css("demo/toolbar.css")};\n` +
    `export const SORTABLE_CSS = ${css("demo/sortable.css")};\n` +
    `export const MOTION_CSS = ${css("demo/motion.css")};\n` +
    `export const TABLE_CSS = ${css("demo/table.css")};\n` +
    `export const DROPDOWN_CSS = ${css("demo/dropdown.css")};\n`,
);

const esbuild = requireDom("esbuild");
await esbuild.build({
  entryPoints: [path.join(HERE, "evg-harness.js")],
  bundle: true,
  format: "esm",
  outfile: path.join(HERE, "bundle-evg.js"),
  logLevel: "info",
});
await esbuild.build({
  entryPoints: [path.join(HERE, "dom-app.jsx")],
  bundle: true,
  format: "esm",
  outfile: path.join(HERE, "bundle-dom.js"),
  loader: { ".jsx": "jsx" },
  define: { "process.env.NODE_ENV": '"production"' },
  nodePaths: [path.join(DOM_DIR, "node_modules")],
  logLevel: "info",
});
