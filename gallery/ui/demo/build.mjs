/**
 * Bundle the menubar demo page.
 *
 * The stylesheet is generated into a module rather than fetched, so the page
 * and `npm run ui:menubar:png` style the tree from exactly the same text and
 * cannot drift. esbuild comes from the conformance reference host, so there is
 * one install for the playground, the gate and this.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { assertDomInstalled, MissingDomDeps } from "../conformance/dom-adapter.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const UI = path.join(HERE, "..");
const DOM_DIR = path.join(UI, "conformance", "dom");
const domRequire = createRequire(path.join(DOM_DIR, "package.json"));

function requireDom(name) {
  try {
    assertDomInstalled();
    return domRequire(name);
  } catch (e) {
    console.error(e instanceof MissingDomDeps ? e.message : String(e));
    process.exit(3);
  }
}

for (const name of ["MenubarDemo", "ToolbarDemo", "SortableDemo"]) {
  if (!fs.existsSync(path.join(UI, "bin", name + ".cjs"))) {
    console.error(`compiled ${name} missing — run \`npm run ui:demo:build\` first`);
    process.exit(3);
  }
}

// One-line re-exports, so the page imports paths that are the same in the
// bundle and in the editor rather than reaching into ../bin.
fs.writeFileSync(
  path.join(HERE, "generated-host.js"),
  "// Generated by demo/build.mjs — do not edit.\n" +
    'export { MenubarDemo } from "../bin/MenubarDemo.cjs";\n' +
    'export { ToolbarDemo } from "../bin/ToolbarDemo.cjs";\n' +
    'export { SortableDemo } from "../bin/SortableDemo.cjs";\n',
);

const css = (f) => JSON.stringify(fs.readFileSync(path.join(HERE, f), "utf8"));
fs.writeFileSync(
  path.join(HERE, "generated.js"),
  "// Generated by demo/build.mjs — do not edit.\n" +
    `export const MENUBAR_CSS = ${css("menubar.css")};\n` +
    `export const TOOLBAR_CSS = ${css("toolbar.css")};\n` +
    `export const SORTABLE_CSS = ${css("sortable.css")};\n`,
);

const esbuild = requireDom("esbuild");
await esbuild.build({
  entryPoints: [path.join(HERE, "main.js")],
  bundle: true,
  format: "esm",
  outfile: path.join(HERE, "bundle.js"),
  logLevel: "info",
});
