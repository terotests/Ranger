/**
 * Bundle the playground.
 *
 * Fixtures and the theme are generated into a module rather than fetched, so
 * the page has exactly the specs the gate has and cannot drift from them.
 * Dependencies come from the conformance reference host, so there is one
 * install for both.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const UI = path.join(HERE, "..");
const DOM_DIR = path.join(UI, "conformance", "dom");
const domRequire = createRequire(path.join(DOM_DIR, "package.json"));

function requireDom(name) {
  try {
    return domRequire(name);
  } catch {
    console.error(
      "the reference host is not installed — run:\n" +
        "  npm run ui:conformance:install",
    );
    process.exit(3);
  }
}

const HOST = path.join(UI, "bin", "ui_host.cjs");
if (!fs.existsSync(HOST)) {
  console.error("compiled host missing — run `npm run ui:build` first");
  process.exit(3);
}

const specsDir = path.join(UI, "conformance", "specs");
const specs = fs
  .readdirSync(specsDir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join(specsDir, f), "utf8")));

const themeCss = fs.readFileSync(path.join(UI, "theme", "base.css"), "utf8");

fs.writeFileSync(
  path.join(HERE, "generated.js"),
  "// Generated by web/build.mjs — do not edit.\n" +
    `export const SPECS = ${JSON.stringify(specs, null, 1)};\n` +
    `export const THEME_CSS = ${JSON.stringify(themeCss)};\n`,
);

const esbuild = requireDom("esbuild");
await esbuild.build({
  entryPoints: [path.join(HERE, "main.jsx")],
  bundle: true,
  format: "esm",
  outfile: path.join(HERE, "bundle.js"),
  loader: { ".jsx": "jsx" },
  define: { "process.env.NODE_ENV": '"production"' },
  nodePaths: [path.join(DOM_DIR, "node_modules")],
  logLevel: "info",
});
